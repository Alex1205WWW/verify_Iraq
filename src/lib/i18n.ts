// Interface language. Values stored in the database stay English — expertise,
// document slot labels and status keys are all canonical English strings and
// are translated only at the point of display, so switching language never
// rewrites data.

export const LANGS = ["en", "ar"] as const;
export type Lang = (typeof LANGS)[number];

export const LANG_NAME: Record<Lang, string> = {
  en: "English",
  ar: "العربية",
};

export function dirFor(lang: Lang): "ltr" | "rtl" {
  return lang === "ar" ? "rtl" : "ltr";
}

export function isLang(v: unknown): v is Lang {
  return typeof v === "string" && (LANGS as readonly string[]).includes(v);
}

