/**
 * `en` is declared `as const` so every key is checked and typos are caught,
 * but that also makes each value its own literal type — which no translation
 * could ever satisfy. Widening the leaves back to `string` keeps the key
 * structure enforced while letting any language supply the words.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

