/**
 * Turns the existing Prisma seed into plain SQL that Cloudflare D1 can import.
 *
 * D1 cannot run the seed directly: `prisma db push` does not work against D1
 * on Prisma 6, and the seed script expects a local SQLite file. So:
 *
 *   1. build a throwaway SQLite file from the same schema
 *   2. run the real seed into it, unchanged
 *   3. read every row back out and write INSERT statements
 *
 * The output reproduces the seed exactly - same ids, same bcrypt hashes, same
 * timestamps in the same storage format - because it is read from what Prisma
 * itself wrote.
 *
 * Output: seed/seed.sql, applied with
 *   wrangler d1 execute dispatch --remote --file=seed/seed.sql
 */
import { execSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";

const dir = mkdtempSync(path.join(tmpdir(), "dispatch-seed-"));
const dbFile = path.join(dir, "seed.db").replaceAll("\\", "/");
const env = { ...process.env, DATABASE_URL: `file:${dbFile}` };

try {
  console.log("Building a throwaway database from the schema...");
  execSync("npx prisma db push --skip-generate", { env, stdio: "inherit" });

  console.log("Running the real seed into it...");
  execSync("node prisma/seed.mjs", { env, stdio: "inherit" });

  const sqlite = new DatabaseSync(dbFile, { readOnly: true });

  const tables = sqlite
    .prepare(
      "SELECT name FROM sqlite_master WHERE type = 'table' " +
        "AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_prisma_%'",
    )
    .all()
    .map((r) => r.name);

  // Order tables so a referenced table is inserted before any table that
  // points at it. Self-references (User.approvedById) are ignored here and
  // covered by deferring foreign key checks instead.
  const deps = new Map(
    tables.map((t) => [
      t,
      new Set(
        sqlite
          .prepare(`PRAGMA foreign_key_list("${t}")`)
          .all()
          .map((fk) => fk.table)
          .filter((target) => target !== t && tables.includes(target)),
      ),
    ]),
  );

  const ordered = [];
  const done = new Set();
  const visit = (t, trail = new Set()) => {
    if (done.has(t)) return;
    if (trail.has(t)) throw new Error(`Foreign key cycle through ${t}`);
    trail.add(t);
    for (const d of deps.get(t)) visit(d, trail);
    trail.delete(t);
    done.add(t);
    ordered.push(t);
  };
  tables.forEach((t) => visit(t));

  const literal = (v) => {
    if (v === null || v === undefined) return "NULL";
    if (typeof v === "number" || typeof v === "bigint") return String(v);
    if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString("hex")}'`;
    return `'${String(v).replaceAll("'", "''")}'`;
  };

  const lines = [
    "-- Generated by scripts/export-seed-sql.mjs. Do not edit by hand.",
    "-- Demo data only. Change the seeded passwords before sharing a link.",
    "PRAGMA defer_foreign_keys = true;",
    "",
  ];

  let rows = 0;
  for (const t of ordered) {
    const data = sqlite.prepare(`SELECT * FROM "${t}"`).all();
    if (data.length === 0) continue;
    const cols = Object.keys(data[0]);
    lines.push(`-- ${t} (${data.length})`);
    for (const row of data) {
      lines.push(
        `INSERT INTO "${t}" (${cols.map((c) => `"${c}"`).join(", ")}) ` +
          `VALUES (${cols.map((c) => literal(row[c])).join(", ")});`,
      );
      rows++;
    }
    lines.push("");
  }

  sqlite.close();
  writeFileSync("seed/seed.sql", lines.join("\n"));
  console.log(`Wrote seed/seed.sql: ${rows} rows across ${ordered.length} tables.`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
